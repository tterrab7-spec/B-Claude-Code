import { usd } from '../../lib/money.js';

export interface ReportData {
  project: { id: string; name: string; address: string | null; stage: string; programType: string };
  period: string;
  budget: { revisedCents: number; committedCents: number; paidCents: number; forecastAtCompletionCents: number; varianceCents: number; percentComplete: number };
  schedule: { status: string; daysLate: number; nextMilestone: { name: string; phase: string; plannedEnd: string | null } | null; milestonesComplete: number; milestonesTotal: number };
  draws: { number: number; status: string; requestedCents: number; fundedCents: number; periodEnd: string }[];
  loans: { lender: string; commitmentCents: number; drawnCents: number }[];
  photos: { id: string; fileName: string }[];
  updates: { body: string; createdAt: string }[];
  investors: { commitmentCents: number; fundedCents: number; ownershipPct: number }[];
  updatedReturns: { projectedProfitCents: number | null; projectedRoi: number | null; note: string };
}

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]!));

export function renderInvestorReport(d: ReportData): string {
  const row = (k: string, v: string) => `<tr><td style="padding:6px 10px;color:#555">${esc(k)}</td><td style="padding:6px 10px;text-align:right;font-weight:600">${esc(v)}</td></tr>`;
  const varianceTone = d.budget.varianceCents < 0 ? '#b42318' : '#067647';
  return `<!doctype html><html><head><meta charset="utf-8"><title>${esc(d.project.name)} — Investor Report ${esc(d.period)}</title></head>
<body style="font-family:Inter,Arial,sans-serif;max-width:760px;margin:0 auto;padding:32px;color:#111">
<h1 style="margin:0 0 4px;font-size:24px">${esc(d.project.name)}</h1>
<p style="margin:0 0 24px;color:#555">Investor report · ${esc(d.period)} · ${esc(d.project.address ?? '')} · Stage: ${esc(d.project.stage)}</p>
<h2 style="font-size:16px;margin:24px 0 8px">Budget</h2>
<table style="width:100%;border-collapse:collapse;border:1px solid #eee">
${row('Revised budget', usd(d.budget.revisedCents))}${row('Committed', usd(d.budget.committedCents))}${row('Paid to date', usd(d.budget.paidCents))}${row('Forecast at completion', usd(d.budget.forecastAtCompletionCents))}
<tr><td style="padding:6px 10px;color:#555">Variance (under / over)</td><td style="padding:6px 10px;text-align:right;font-weight:600;color:${varianceTone}">${d.budget.varianceCents < 0 ? '-' : ''}${esc(usd(Math.abs(d.budget.varianceCents)))}</td></tr>
${row('Percent complete (cost basis)', d.budget.percentComplete + '%')}
</table>
<h2 style="font-size:16px;margin:24px 0 8px">Schedule</h2>
<p>Status: <strong>${esc(d.schedule.status.replace('_', ' '))}</strong>${d.schedule.daysLate ? ` (${d.schedule.daysLate} days behind)` : ''}. Milestones complete: ${d.schedule.milestonesComplete}/${d.schedule.milestonesTotal}.${d.schedule.nextMilestone ? ` Next: ${esc(d.schedule.nextMilestone.name)} (${esc(d.schedule.nextMilestone.phase)}${d.schedule.nextMilestone.plannedEnd ? `, due ${esc(d.schedule.nextMilestone.plannedEnd)}` : ''}).` : ''}</p>
<h2 style="font-size:16px;margin:24px 0 8px">Financing &amp; draws</h2>
<table style="width:100%;border-collapse:collapse;border:1px solid #eee">
${d.loans.map((l) => row(`${l.lender} — drawn / commitment`, `${usd(l.drawnCents)} / ${usd(l.commitmentCents)}`)).join('')}
${d.draws.map((dr) => row(`Draw #${dr.number} (${dr.status}, period ending ${dr.periodEnd})`, dr.status === 'funded' ? usd(dr.fundedCents) : usd(dr.requestedCents))).join('') || row('Draws', 'None this period')}
</table>
<h2 style="font-size:16px;margin:24px 0 8px">Updates</h2>
${d.updates.length ? d.updates.map((u) => `<p style="margin:0 0 10px"><span style="color:#777">${esc(u.createdAt.slice(0, 10))}</span> — ${esc(u.body)}</p>`).join('') : '<p style="color:#777">No owner updates posted this period.</p>'}
<h2 style="font-size:16px;margin:24px 0 8px">Photos</h2>
<p style="color:#777">${d.photos.length ? d.photos.map((p) => esc(p.fileName)).join(', ') : 'No photos attached this period.'}</p>
<h2 style="font-size:16px;margin:24px 0 8px">Updated return projection</h2>
<p>${d.updatedReturns.projectedProfitCents !== null ? `Projected profit ${esc(usd(d.updatedReturns.projectedProfitCents))}${d.updatedReturns.projectedRoi !== null ? ` · projected ROI ${Math.round(d.updatedReturns.projectedRoi * 100)}%` : ''}. ` : ''}${esc(d.updatedReturns.note)}</p>
<p style="margin-top:32px;font-size:12px;color:#999">Generated by DirtBid Build. Figures are from the project ledger as of the generation date and are not audited.</p>
</body></html>`;
}
